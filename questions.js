/* 数値問題の選択肢を組み立てる。誤答は重複・非有限を除いて先頭3つを採用 */
function build(correct, wrongs, unit){
  const f = v => num(v) + (unit||"");
  const ct = f(correct);
  const used = new Set([ct]);
  const ws = [];
  for(const w of wrongs){
    if(!isFinite(w.v)) continue;
    const t = f(w.v);
    if(used.has(t)) continue;
    used.add(t); ws.push({t, why:w.why});
    if(ws.length===3) break;
  }
  let k = 2;
  while(ws.length<3){
    const t = f(Math.round(correct*k*10)/10);
    if(!used.has(t)){ used.add(t); ws.push({t, why:"計算の途中で係数を取り違えた場合に出る値です。"}); }
    k += 0.5;
  }
  const arr = shuffle([{t:ct, ok:true, why:""}].concat(ws.map(w=>({t:w.t, ok:false, why:w.why}))));
  return {
    choices: arr.map(a=>a.t),
    answer: arr.findIndex(a=>a.ok),
    notes: arr.map(a=>a.why)
  };
}

