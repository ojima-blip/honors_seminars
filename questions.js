const pick = a => a[Math.floor(Math.random()*a.length)];
const num = v => {
  const r = Math.round(v*1000)/1000;
  return String(r).replace(/\B(?=(\d{3})+(?!\d))/g, ",");
};
function shuffle(a){
  const b = a.slice();
  for(let i=b.length-1;i>0;i--){const j=Math.floor(Math.random()*(i+1));[b[i],b[j]]=[b[j],b[i]];}
  return b;
}
/* 文字列の選択肢を組み立てる（数値では表せない答え用） */
function buildText(correct, cands){
  const used = new Set([correct]); const ws = [];
  for(const c of cands){ if(used.has(c.t)) continue; used.add(c.t); ws.push(c); if(ws.length===3) break; }
  const arr = shuffle([{t:correct, ok:true, why:""}].concat(ws.map(w=>({t:w.t, ok:false, why:w.why}))));
  return {choices:arr.map(a=>a.t), answer:arr.findIndex(a=>a.ok), notes:arr.map(a=>a.why)};
}

