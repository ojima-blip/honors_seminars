/* 出題のたびに数値と選択肢の並びを作り直す */
function materialize(q){
  const g = (q.type === "gen") ? q.gen() : null;
  const base = g
    ? {stem:g.stem, give:g.give||"", giveHtml:g.giveHtml||"", choices:g.choices,
       answer:g.answer, why:g.notes||[], explain:g.explain}
    : {stem:q.stem, give:q.give||"", giveHtml:q.giveHtml||"", choices:q.choices,
       answer:q.answer, why:q.why||[], explain:q.explain};
  /* 正答位置が偏らないよう、固定問題も出題のたびに選択肢を並べ替える */
  const order = shuffle(base.choices.map((_,i)=>i));
  return {
    id:q.id, tag:q.tag, level:q.level, gen:(q.type==="gen"),
    stem:base.stem, give:base.give, giveHtml:base.giveHtml,
    choices: order.map(i=>base.choices[i]),
    answer:  order.indexOf(base.answer),
    why:     order.map(i=>base.why[i]||""),
    explain: base.explain
  };
}
